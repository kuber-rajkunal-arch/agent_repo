-- VT_STG_EMPLOYEE
CREATE TEMP TABLE VT_STG_EMPLOYEE AS
SELECT *
FROM HRA_STG_WORKDAY_V.STG_EMPLOYEE
WHERE CAST(SOURCE_FILE_DTTM AS DATE) = (SELECT MAX(CAST(SOURCE_FILE_DTTM AS DATE)) FROM HRA_STG_WORKDAY_V.STG_EMPLOYEE);

-- VT_STG_ORG_HIERARCHY
CREATE TEMP TABLE VT_STG_ORG_HIERARCHY AS
SELECT SUPERVISORY_ORGANIZATION_ID, SUPERVISORY_ORGANIZATION_NAME, FUNCTIONAL_GROUP_CODE, BUSINESS_UNIT_NAME, FUNCTIONAL_GROUP_ID, FUNCTIONAL_GROUP_NAME
