CREATE OR REPLACE TABLE HRA_CORE_T.ASSOCIATE_ADGROUP_ANOMALY_SNAPSHOT AS
SELECT
    A.ASSOC_USER_NAME,
    A.ASSOC_ADGROUP_ID,
    B.EMPLOYEE_ID,
    B.LEGAL_FIRST_NAME,
    B.LEGAL_MIDDLE_NAME,
    B.LEGAL_LAST_NAME,
    B.EMPLOYMENT_STATUS,
    B.HIRE_DATE,
    CASE WHEN B.HIRE_DATE < B.TERMINATION_DATE THEN B.TERMINATION_DATE END AS TERM_DATE,
    ORG.FUNCTIONAL_GROUP_NAME,
    J.JOB_TITLE,
    CURRENT_DATE() AS SNAPSHOT_DATE
FROM (
    SELECT DISTINCT TRIM(ASSOC_USER_NAME) AS ASSOC_USER_NAME, TRIM(ASSOC_ADGROUP_ID) AS ASSOC_ADGROUP_ID
    FROM HRA_CORE_V.ASSOCIATE_ADGROUP_SNAPSHOT
    EXCEPT DISTINCT
    SELECT DISTINCT TRIM(NTID) AS ASSOC_USER_NAME, TRIM(ADGRP_ID) AS ASSOC_ADGROUP_ID
    FROM VT_ADGRP_NTID
) AS A
LEFT JOIN (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY NTID ORDER BY SOURCE_FILE_DTTM DESC) as rn
    FROM HRA_STG_WORKDAY_V.STG_EMPLOYEE
) AS B ON A.ASSOC_USER_NAME = B.NTID AND B.rn = 1
LEFT JOIN VT_STG_ORG_HIERARCHY AS ORG ON B.SUPERVISORY_ORGANIZATION_ID = ORG.SUPERVISORY_ORGANIZATION_ID
LEFT JOIN VT_STG_JOB_PROFILE AS J ON B.JOB_ID = J.JOB_CODE;