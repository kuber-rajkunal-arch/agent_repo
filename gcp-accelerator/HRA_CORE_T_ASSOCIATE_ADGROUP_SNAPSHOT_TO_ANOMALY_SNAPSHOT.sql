-- VT_STG_JOB_PROFILE
CREATE TEMP TABLE VT_STG_JOB_PROFILE AS
SELECT JOB_CODE, JOB_TITLE, JOB_FAMILY, EXECUTIVE_INDICATOR
FROM HRA_STG_WORKDAY_V.STG_JOB_PROFILE
WHERE Inactive = 'False'
AND CAST(SOURCE_FILE_DTTM AS DATE) = (SELECT CAST(MAX(SOURCE_FILE_DTTM) AS DATE) FROM HRA_STG_WORKDAY_V.STG_JOB_PROFILE);

