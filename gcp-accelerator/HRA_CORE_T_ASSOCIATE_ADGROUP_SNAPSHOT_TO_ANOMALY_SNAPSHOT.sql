    CAST(EM.SOURCE_FILE_DTTM AS DATE) = (SELECT MAX(CAST(SOURCE_FILE_DTTM AS DATE)) FROM HRA_STG_WORKDAY_V.STG_EM_PERSONAL)
    AND EM.TERMINATED = 'N';

