-- Test Name: test_positive_balance_filter
WITH
Mock_CBL0005_ACCT_REC AS (
  SELECT 'ACCT001' AS ACCT_NO, 1500.75 AS ACCT_BALANCE, DATE '2023-10-26' AS LAST_TRAN_DATE, 'Alice' AS CUST_NAME
  UNION ALL
  SELECT 'ACCT002', 0.00, DATE '2023-10-25', 'Bob'
  UNION ALL
  SELECT 'ACCT003', -50.25, DATE '2023-10-24', 'Charlie'
  UNION ALL
  SELECT 'ACCT004', 99.99, DATE '2023-10-27', 'Diana'
  UNION ALL
  SELECT 'ACCT000', 1.00, DATE '2023-01-01', 'Zane'
),
CBL0005_FINANCIAL_REPORT AS (
  WITH
  ReportData AS (
    SELECT ACCT_NO, ACCT_BALANCE, LAST_TRAN_DATE, CUST_NAME FROM Mock_CBL0005_ACCT_REC WHERE ACCT_BALANCE > 0
  )
  SELECT CURRENT_DATE() AS REPORT_GENERATION_DATE, d.ACCT_NO, d.CUST_NAME, d.ACCT_BALANCE, d.LAST_TRAN_DATE FROM ReportData d ORDER BY d.ACCT_NO
)
SELECT ACCT_NO, ACCT_BALANCE FROM CBL0005_FINANCIAL_REPORT WHERE ACCT_BALANCE <= 0;

